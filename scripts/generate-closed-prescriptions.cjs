const fs = require('fs');
const path = require('path');

const PREFIXES = ['dddd', 'eeee', 'ffff', 'cccc', 'bbbb'];
const OUTPUT = path.join(__dirname, 'closed-prescription-seed.sql');

const patients = [];
for (let i = 1001; i <= 1025; i++) patients.push({ id: i, dept: 2 });
for (let i = 1026; i <= 1050; i++) patients.push({ id: i, dept: 1 });
for (let i = 2001; i <= 2020; i++) patients.push({ id: i, dept: 2 });
for (let i = 2021; i <= 2040; i++) patients.push({ id: i, dept: 1 });

const lines = [];
lines.push('-- Closed (Finished) prescription lists — 1-5 per patient');
lines.push('-- Generated by scripts/generate-closed-prescriptions.cjs');
lines.push('');

for (const p of patients) {
  const count = (p.id % 5) + 1; // 1-5 per patient
  for (let j = 0; j < count; j++) {
    const prefix = PREFIXES[j];
    const seq = String(p.id).slice(-4) + String(j + 1).padStart(2, '0');
    const lastSegment = seq.padEnd(12, '0');
    const id = `${prefix}${p.id}-${p.id}-${p.id}-${p.id}-${lastSegment}`;
    const docName = `Листок лікарських призначень №${j + 2}`;
    const createdAt = `NOW() - INTERVAL '${count - j} days'`;
    lines.push(
      `INSERT INTO prescription_lists (id, patient_id, department_id, document_name, status, editing_user_id, editing_started_at, created_at, created_by, updated_at, updated_by, version, is_deleted) VALUES ('${id}', ${p.id}, ${p.dept}, '${docName}', 'Finished', NULL, NULL, ${createdAt}, 11, ${createdAt}, 11, 0, FALSE) ON CONFLICT (id) DO NOTHING;`
    );
  }
}

lines.push('');
fs.writeFileSync(OUTPUT, lines.join('\n'), 'utf8');
console.log(`Generated ${OUTPUT}`);
